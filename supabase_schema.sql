drop policy if exists "products public read" on public.products;
create policy "products public read" on public.products for select using (is_active=true);
drop policy if exists "settings public read" on public.site_settings;
create policy "settings public read" on public.site_settings for select using (true);

create policy "profile own read" on public.profiles for select using (id=auth.uid());
create policy "wallet own read" on public.wallets for select using (user_id=auth.uid());
create policy "orders own read" on public.orders for select using (user_id=auth.uid());
create policy "tx own read" on public.wallet_transactions for select using (user_id=auth.uid());
create policy "deposit own insert" on public.deposit_requests for insert with check (user_id=auth.uid());
create policy "deposit own read" on public.deposit_requests for select using (user_id=auth.uid());
create policy "withdraw own insert" on public.withdraw_requests for insert with check (user_id=auth.uid());
create policy "withdraw own read" on public.withdraw_requests for select using (user_id=auth.uid());

